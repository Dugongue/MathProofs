from collections import defaultdict
from itertools import product
from math import gcd


def digits(value, base, length):
    result = []
    for _ in range(length):
        value, digit = divmod(value, base)
        result.append(digit)
    return result


class Field:
    """Exact polynomial-basis arithmetic modulo a monic irreducible polynomial."""

    def __init__(self, prime, modulus):
        self.p = prime
        self.degree = len(modulus)
        self.size = prime ** self.degree
        self.elements = range(self.size)
        self.modulus = modulus
        self.coords = [digits(value, prime, self.degree) for value in self.elements]
        self.sums = [[self.pack(x + y for x, y in zip(self.coords[a], self.coords[b]))
                      for b in self.elements] for a in self.elements]
        self.products = [[self.multiply(a, b) for b in self.elements] for a in self.elements]
        assert all(1 in self.products[x] for x in self.elements if x)

    def pack(self, coefficients):
        return sum((c % self.p) * self.p ** i for i, c in enumerate(coefficients))

    def multiply(self, a, b):
        coefficients = [0] * (2 * self.degree - 1)
        for i, x in enumerate(self.coords[a]):
            for j, y in enumerate(self.coords[b]):
                coefficients[i + j] += x * y
        for i in range(len(coefficients) - 1, self.degree - 1, -1):
            for j, x in enumerate(self.modulus):
                coefficients[i - self.degree + j] -= x * coefficients[i]
        return self.pack(coefficients[:self.degree])

    def power(self, x, n):
        answer = 1
        while n:
            if n % 2:
                answer = self.products[answer][x]
            x = self.products[x][x]
            n //= 2
        return answer


def pure_power_checks(field):
    def multiply(left, right):
        result = defaultdict(int)
        for m, x in left.items():
            for n, y in right.items():
                exponent = tuple(a + b for a, b in zip(m, n))
                result[exponent] = field.sums[result[exponent]][field.products[x][y]]
        return {exponent: value for exponent, value in result.items() if value}

    variables = tuple(tuple(int(i == j) for j in range(3)) for i in range(3))
    for coefficients in product(field.elements, repeat=3):
        linear_form = dict(zip(variables, coefficients))
        power = {(0, 0, 0): 1}
        for _ in range(field.p):
            power = multiply(power, linear_form)
        expected = {tuple(field.p * j for j in monomial): field.power(x, field.p)
                    for monomial, x in linear_form.items() if x}
        assert power == expected
    return field.size ** 3


def matrix_cycle_checks(field):
    frobenius = [field.power(x, field.p) for x in field.elements]
    accepted = [0] * (field.degree + 1)
    for a, b, c, d in product(field.elements, repeat=4):
        if field.products[a][d] == field.products[b][c]:
            continue
        matrix = (a, b, c, d)
        layer = matrix
        for length in range(1, field.degree + 1):
            layer = tuple(frobenius[x] for x in layer)
            accepted[length] += layer == matrix
    for length in range(1, field.degree + 1):
        subfield = field.p ** gcd(length, field.degree)
        assert accepted[length] == (subfield ** 2 - 1) * (subfield ** 2 - subfield)
    return field.size ** 4


def restriction_checks(field):
    prime = field.p
    degree = field.degree
    theta = prime
    for coefficients in product(range(prime), repeat=degree ** 2):
        matrix = [coefficients[i:i + degree] for i in range(0, len(coefficients), degree)]

        def linear_map(x):
            return field.pack(sum(a * b for a, b in zip(row, field.coords[x])) for row in matrix)

        commutes = all(linear_map(field.products[theta][x]) == field.products[theta][linear_map(x)]
                       for x in field.elements)
        scalar = linear_map(1)
        assert commutes == all(linear_map(x) == field.products[scalar][x] for x in field.elements)
    return prime ** (degree ** 2)


def extension_trap(field):
    # F4 as the algebra generated by a root of X^2 + X + 1 over F2.
    # Over F4, evaluation at the two roots converts this multiplication to a split one.
    theta = 2
    root_two = field.power(theta, 2)
    assert root_two != theta
    assert all(field.sums[field.sums[field.power(x, 2)][x]][1] == 0 for x in (theta, root_two))

    def evaluate(vector, root):
        a, b = vector
        return field.sums[a][field.products[b][root]]

    def source_product(x, y):
        a, b = x
        c, d = y
        ac, ad = field.products[a][c], field.products[a][d]
        bc, bd = field.products[b][c], field.products[b][d]
        return field.sums[ac][bd], field.sums[field.sums[ad][bc]][bd]

    for a, b, c, d in product(field.elements, repeat=4):
        for root in (theta, root_two):
            assert evaluate(source_product((a, b), (c, d)), root) == field.products[
                evaluate((a, b), root)][evaluate((c, d), root)]
    # The evaluation change of basis is invertible but cannot pass a one-link F2 guard.
    assert theta != root_two and field.power(theta, 2) != theta
    # The original field product has no nonzero zero-divisor pairs over F2.
    source_vectors = [(1, 0), (0, 1), (1, 1)]
    assert all(source_product(x, y) != (0, 0) for x, y in product(source_vectors, repeat=2))
    # The split product annihilates this pair of nonzero inputs.
    assert tuple(field.products[x][y] for x, y in zip((1, 0), (0, 1))) == (0, 0)
    return 2 * field.size ** 4


if __name__ == '__main__':
    fields = [Field(2, (1, 1)), Field(2, (1, 1, 0)), Field(2, (1, 1, 0, 0)),
              Field(3, (1, 0)), Field(3, (1, 2, 0))]
    form_count = sum(pure_power_checks(field) for field in fields)
    cycle_count = sum(matrix_cycle_checks(field) for field in fields[:-1])
    restriction_count = sum(restriction_checks(fields[i]) for i in (0, 1, 3, 4))
    extension_count = extension_trap(fields[0])
    print(f'PASS: {form_count} pure powers, {cycle_count} candidate matrices, '
          f'{restriction_count} restriction maps and {extension_count} extension-trap evaluations')
