"""Explicit kernel generators modulo 2^B; exact controls, with all column transforms."""
import sys,pathlib
from sympy import Matrix,diag

def kernel_generators(M,q):
    assert q>=4 and q&(q-1)==0
    A=[[int(x)%q for x in row] for row in M.tolist()];m=len(A);n=M.cols;V=[[int(i==j) for j in range(n)] for i in range(n)];piv=[];k=0
    while k<min(m,n):
        best=None;val=q
        for i in range(k,m):
            for j in range(k,n):
                x=A[i][j]
                if x and (x&-x)<val:best=(i,j);val=x&-x
                if val==1:break
            if val==1:break
        if best is None:break
        i,j=best;A[k],A[i]=A[i],A[k]
        if j!=k:
            for row in A:row[k],row[j]=row[j],row[k]
            for row in V:row[k],row[j]=row[j],row[k]
        pivot=val;inv=pow(A[k][k]//pivot,-1,q);A[k]=[(x*inv)%q for x in A[k]];assert A[k][k]==pivot
        for i in range(k+1,m):
            if A[i][k]:
                assert A[i][k]%pivot==0
                f=A[i][k]//pivot;A[i]=[(x-f*y)%q for x,y in zip(A[i],A[k])]
        for j in range(k+1,n):
            if A[k][j]:
                assert A[k][j]%pivot==0
                f=A[k][j]//pivot
                for i in range(n):V[i][j]=(V[i][j]-f*V[i][k])%q
                A[k][j]=0
        piv.append(pivot);k+=1
    ds=piv+[q]*(n-len(piv))
    # Mod-q free coordinates are generated by V e_j/q as turns; nonzero
    # pivots are generated by V e_j/pivot. Diagonal q means free modulo q.
    return diag(*ds),None,Matrix(V)
